"""End-to-end smoke test against the Docker stack (nginx :8080 -> gunicorn -> Postgres/Redis/Celery)."""
import json
import sys
import time
import urllib.error
import urllib.request
import uuid

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8080"
results = []


def call(method, path, token=None, ws=None, body=None, raw=None, ctype=None):
    headers = {}
    data = None
    if body is not None:
        data, headers["Content-Type"] = json.dumps(body).encode(), "application/json"
    if raw is not None:
        data, headers["Content-Type"] = raw, ctype
    if token:
        headers["Authorization"] = f"Bearer {token}"
    if ws:
        headers["X-Workspace"] = ws
    req = urllib.request.Request(BASE + path, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return r.status, r.read(), r.headers
    except urllib.error.HTTPError as e:
        return e.code, e.read(), e.headers


def check(name, cond, extra=""):
    results.append(cond)
    print(("PASS " if cond else "FAIL ") + name + (f"  [{extra}]" if extra and not cond else ""))


def login(email):
    s, b, _ = call("POST", "/api/auth/login/", body={"email": email, "password": "Demo@1234"})
    check(f"login {email}", s == 200, f"{s} {b[:200]}")
    return json.loads(b)["access"]


def items(b):
    d = json.loads(b)
    return d["results"] if isinstance(d, dict) and "results" in d else d


owner = login("owner@acme.test")
viewer = login("viewer@acme.test")
globex = login("owner@globex.test")

s, b, _ = call("GET", "/api/auth/me/", owner)
check("me", s == 200)
s, b, _ = call("GET", "/api/projects/", owner, "acme")
projects = items(b)
check("acme projects listed", s == 200 and len(projects) >= 3, f"{s}")
s, b, _ = call("GET", "/api/issues/?page_size=5", owner, "acme")
issues = items(b)
check("acme issues listed", s == 200 and len(issues) > 0, f"{s} {b[:200]}")
issue_key = issues[0]["key"]
s, _, _ = call("GET", "/api/dashboard/", owner, "acme")
check("dashboard", s == 200)
s, _, _ = call("GET", "/api/boards/", owner, "acme")
check("boards", s == 200)
s, _, _ = call("GET", "/api/sprints/", owner, "acme")
check("sprints", s == 200)

# tenant isolation + roles
s, _, _ = call("GET", "/api/projects/", globex, "acme")
check("globex owner blocked from acme", s in (403, 404), f"{s}")
s, _, _ = call("GET", "/api/audit-log/", viewer, "acme")
check("viewer blocked from audit log", s == 403, f"{s}")
s, _, _ = call("POST", f"/api/issues/{issue_key}/comments/", viewer, "acme", body={"body": "x"})
check("viewer cannot comment", s == 403, f"{s}")
s, _, _ = call("GET", "/api/audit-log/", owner, "acme")
check("owner reads audit log", s == 200)

# collaboration (also fans out to Celery: webhooks/notifications)
s, b, _ = call("POST", f"/api/issues/{issue_key}/comments/", owner, "acme", body={"body": "Docker smoke test comment"})
check("comment created", s == 201, f"{s} {b[:200]}")
boundary = uuid.uuid4().hex
payload = (f"--{boundary}\r\nContent-Disposition: form-data; name=\"file\"; filename=\"smoke.txt\"\r\n"
           f"Content-Type: text/plain\r\n\r\nhello from docker\r\n--{boundary}--\r\n").encode()
s, b, _ = call("POST", f"/api/issues/{issue_key}/attachments/", owner, "acme", raw=payload,
               ctype=f"multipart/form-data; boundary={boundary}")
check("attachment uploaded", s == 201, f"{s} {b[:200]}")
if s == 201:
    att = json.loads(b)["id"]
    s, b, _ = call("GET", f"/api/attachments/{att}/download/", viewer, "acme")
    check("attachment downloaded by viewer", s == 200 and b == b"hello from docker", f"{s} {b[:80]}")
    s, _, _ = call("DELETE", f"/api/attachments/{att}/", owner, "acme")
    check("attachment cleaned up", s == 204, f"{s}")

# Celery: report generated by the worker container
s, b, _ = call("POST", "/api/reports/", owner, "acme", body={"report_type": "workspace_summary"})
check("report queued", s == 202, f"{s} {b[:200]}")
if s == 202:
    rid = json.loads(b)["id"]
    state = None
    for _ in range(30):
        s, b, _ = call("GET", f"/api/reports/{rid}/", owner, "acme")
        state = json.loads(b)["state"]
        if state in ("ready", "failed"):
            break
        time.sleep(1)
    check("worker generated report", state == "ready", f"state={state}")
    s, b, h = call("GET", f"/api/reports/{rid}/download/", owner, "acme")
    check("report CSV download", s == 200 and "text/csv" in h.get("Content-Type", ""), f"{s}")

s, _, _ = call("GET", "/api/notifications/", owner, "acme")
check("notifications", s == 200)
s, _, _ = call("GET", "/api/webhooks/", owner, "acme")
check("webhooks (admin)", s == 200)
s, b, _ = call("GET", "/api/billing/", owner, "acme")
check("billing status", s == 200, f"{s} {b[:200]}")
s, _, _ = call("POST", "/api/billing/checkout/", viewer, "acme", body={"plan": "pro"})
check("viewer blocked from checkout", s == 403, f"{s}")
s, _, _ = call("POST", "/api/billing/webhook/", raw=b"{}", ctype="application/json")
check("stripe webhook rejects unsigned", s in (400, 503), f"{s}")
s, _, _ = call("GET", "/api/schema/", owner)
check("openapi schema", s == 200)

print(f"\n{sum(results)}/{len(results)} checks passed")
sys.exit(0 if all(results) else 1)
